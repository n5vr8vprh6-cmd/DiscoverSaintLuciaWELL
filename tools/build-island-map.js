#!/usr/bin/env node
/* ============================================================================
   build-island-map — Saint Lucia's coastline, once, into content/island.js
   ----------------------------------------------------------------------------
     node tools/build-island-map.js <path-to-geoBoundaries-LCA-ADM0_simplified.geojson>

   The ASK WELL Understand stage draws the island with the client's villages and
   shortlisted resorts pinned on it. No outline existed anywhere in the estate,
   so this reads a public boundary file and writes the one path the screen
   needs. The source stays outside the repo; only the derived path is committed.

   SOURCE. geoBoundaries (www.geoboundaries.org), gbOpen release, LCA ADM0,
   simplified geometry — CC BY 4.0. The attribution line below travels with the
   generated file and is rendered in the map's <desc>. The main island polygon
   is kept; the Maria Islands off Vieux Fort (two polygons under 100 m across)
   are dropped, because at the size this is drawn they would be dust.

   PROJECTION. Equirectangular, longitude scaled by cos(13.9°) so the island
   keeps its shape, fitted into a 600 × 900 viewBox with a margin. The same
   project() the tool used is written into the module, so a pin placed by
   lat/lng lands where the coastline says it should.
   ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-island-map.js <geojson>'); process.exit(2); }

const gj = JSON.parse(fs.readFileSync(src, 'utf8'));
const feature = gj.features[0];
const geom = feature.geometry;
const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;

/* The island is the polygon with the most vertices; the islets are the rest. */
const main = polys.slice().sort((a, b) => b[0].length - a[0].length)[0][0];

const VIEW_W = 600, VIEW_H = 900, MARGIN = 40;
const LAT0 = 13.9;
const K = Math.cos(LAT0 * Math.PI / 180);

let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
main.forEach(([lng, lat]) => {
  const x = lng * K, y = -lat;
  if (x < minX) minX = x; if (x > maxX) maxX = x;
  if (y < minY) minY = y; if (y > maxY) maxY = y;
});
const scale = Math.min((VIEW_W - 2 * MARGIN) / (maxX - minX), (VIEW_H - 2 * MARGIN) / (maxY - minY));
const offX = (VIEW_W - (maxX - minX) * scale) / 2;
const offY = (VIEW_H - (maxY - minY) * scale) / 2;

const project = (lat, lng) => [
  Math.round(((lng * K) - minX) * scale + offX),
  Math.round(((-lat) - minY) * scale + offY)
];

const d = main.map(([lng, lat], i) => {
  const [x, y] = project(lat, lng);
  return (i === 0 ? 'M' : 'L') + x + ' ' + y;
}).join('') + 'Z';

const lats = main.map((p) => p[1]), lngs = main.map((p) => p[0]);
const bbox = { south: Math.min(...lats), north: Math.max(...lats), west: Math.min(...lngs), east: Math.max(...lngs) };

const out = `/* ============================================================================
   ISLAND — Saint Lucia's coastline as one SVG path, and how to place a point on it
   ----------------------------------------------------------------------------
   GENERATED by tools/build-island-map.js on ${new Date().toISOString().slice(0, 10)}. Do not hand-edit.

   Source: geoBoundaries (www.geoboundaries.org), gbOpen, LCA ADM0 simplified
   geometry, ${main.length} vertices. Licence CC BY 4.0 — the attribution string below
   is rendered wherever the outline is drawn. The Maria Islands are omitted.

   project(lat, lng) is the projection the outline was drawn with —
   equirectangular, longitude scaled by cos(${LAT0}°) — so pins placed by
   coordinate land on the coastline they belong to. Bounding box of the island
   in degrees is exported for tests: a pin outside it is a typo.
   ========================================================================== */
'use strict';

const VIEW = { w: ${VIEW_W}, h: ${VIEW_H} };
const P = { k: ${K}, minX: ${minX}, minY: ${minY}, scale: ${scale}, offX: ${offX}, offY: ${offY} };

function project(lat, lng) {
  return [
    Math.round(((lng * P.k) - P.minX) * P.scale + P.offX),
    Math.round(((-lat) - P.minY) * P.scale + P.offY)
  ];
}

module.exports = {
  viewBox: '0 0 ' + VIEW.w + ' ' + VIEW.h,
  width: VIEW.w,
  height: VIEW.h,
  outline: ${JSON.stringify(d)},
  bbox: ${JSON.stringify(bbox)},
  project,
  attribution: 'Outline: geoBoundaries, CC BY 4.0',
  /* Towns and landmarks for the map's labels. Coordinates from OpenStreetMap
     (Nominatim, 2026-09-10); Soufrière is the town, not the district centroid. */
  labels: [
    { key: 'castries',    name: 'Castries',        lat: 14.0096, lng: -60.9902, anchor: 'end' },
    { key: 'rodney-bay',  name: 'Rodney Bay',      lat: 14.0748, lng: -60.9527, anchor: 'start' },
    { key: 'marigot-bay', name: 'Marigot Bay',     lat: 13.9672, lng: -61.0289, anchor: 'end' },
    { key: 'soufriere',   name: 'Soufrière',       lat: 13.8560, lng: -61.0560, anchor: 'end' },
    { key: 'pitons',      name: 'The Pitons',      lat: 13.8220, lng: -61.0650, anchor: 'end' },
    { key: 'uvf',         name: 'Hewanorra (UVF)', lat: 13.7343, lng: -60.9539, anchor: 'start' },
    { key: 'dennery',     name: 'Dennery',         lat: 13.9236, lng: -60.9248, anchor: 'start' }
  ]
};
`;

const dest = path.join(__dirname, '..', 'content', 'island.js');
fs.writeFileSync(dest, out);
console.log('  wrote ' + path.relative(process.cwd(), dest) + ' — ' + main.length + ' vertices, path ' + d.length + ' chars');
console.log('  bbox ' + JSON.stringify(bbox));
console.log('  Soufrière → ' + project(13.856, -61.056).join(',') + '   Rodney Bay → ' + project(14.0748, -60.9527).join(','));
