#!/usr/bin/env node
/* ============================================================================
   island-map-test — the coastline, the fifteen pins, and what the map emits
   ----------------------------------------------------------------------------
   content/island.js is generated by tools/build-island-map.js from a public
   boundary file; the pins come from `geo` on each deep property in the Field
   Guide, carried into the bank by build-well-knowledge.js. Three things can go
   quietly wrong: a pin typed outside the island (a resort in the sea), a pin
   that projects off the drawing, and a gallery-style whitelist that drops
   `geo` so the map renders empty. This asserts all three, plus the markup
   contract js/hub-design.js relies on.

   Run: node tools/island-map-test.js
   ========================================================================== */
'use strict';
const path = require('path');
const ROOT = path.join(__dirname, '..');
const I = require(path.join(ROOT, 'content', 'island.js'));
const K = require(path.join(ROOT, 'content', 'well-knowledge.generated.js'));
const { islandMap } = require(path.join(ROOT, 'lib', 'components.js'));

let fails = 0, n = 0;
const ok = (label, cond, detail) => { n++; if (cond) console.log('  ok    ' + label); else { fails++; console.log('  FAIL  ' + label + (detail ? '\n        ' + detail : '')); } };

console.log('\n  THE ISLAND');
console.log('  ' + '-'.repeat(62));

/* ── 1. The outline ──────────────────────────────────────────────────────── */
ok('the outline is one closed path', /^M-?\d+ -?\d+(L-?\d+ -?\d+)+Z$/.test(I.outline));
const verts = (I.outline.match(/L/g) || []).length + 1;
ok('with enough vertices to be a coastline, not a blob (' + verts + ')', verts >= 150 && verts <= 600);
ok('the attribution names the source and its licence', /geoBoundaries/.test(I.attribution) && /CC BY/.test(I.attribution));
ok('the bounding box is Saint Lucia', I.bbox.south > 13.6 && I.bbox.north < 14.2 && I.bbox.west > -61.2 && I.bbox.east < -60.8, JSON.stringify(I.bbox));
const [vw, vh] = I.viewBox.split(' ').slice(2).map(Number);
ok('the viewBox is portrait, as the island is', vh > vw);

/* ── 2. Every point of the path is inside the viewBox ────────────────────── */
const pts = I.outline.slice(1, -1).split('L').map((s) => s.split(' ').map(Number));
ok('every vertex lies inside the viewBox', pts.every(([x, y]) => x >= 0 && x <= vw && y >= 0 && y <= vh));

/* ── 3. Labels ───────────────────────────────────────────────────────────── */
ok('labels carry a name and a coordinate inside the island box',
  I.labels.length >= 5 && I.labels.every((l) => l.name && l.lat > I.bbox.south && l.lat < I.bbox.north && l.lng > I.bbox.west && l.lng < I.bbox.east));
ok('Soufrière and Rodney Bay are labelled — the two ends of the shortlist', ['soufriere', 'rodney-bay'].every((k) => I.labels.some((l) => l.key === k)));

/* ── 4. The pins: fifteen deep properties, each with a sourced position ──── */
console.log('\n  THE PINS');
const deep = (K.properties || []).filter((p) => p.collection === 'deep');
ok('fifteen deep properties in the bank', deep.length === 15, String(deep.length));
const missing = deep.filter((p) => !p.geo);
ok('every deep property carries geo (the bank whitelist did not drop it)', missing.length === 0, missing.map((p) => p.slug).join(', '));
const outside = deep.filter((p) => p.geo && !(p.geo.lat > I.bbox.south && p.geo.lat < I.bbox.north && p.geo.lng > I.bbox.west && p.geo.lng < I.bbox.east));
ok('every pin lies inside the island\'s bounding box', outside.length === 0, outside.map((p) => p.slug + ' ' + JSON.stringify(p.geo)).join('; '));
const off = deep.filter((p) => p.geo).map((p) => ({ slug: p.slug, xy: I.project(p.geo.lat, p.geo.lng) })).filter((p) => p.xy[0] < 0 || p.xy[0] > vw || p.xy[1] < 0 || p.xy[1] > vh);
ok('every pin projects inside the drawing', off.length === 0, off.map((p) => p.slug).join(', '));
ok('every pin names its town', deep.every((p) => p.geo && p.geo.town && p.geo.town.length > 3));
const approx = deep.filter((p) => p.geo && p.geo.approx).length;
ok('approximate pins are marked, and there are not too many (' + approx + ')', approx <= 7);
/* The west coast is where most of the shortlist lives; Soufrière pins must
   project west (left) of Rodney Bay pins. */
const souf = deep.filter((p) => /Soufrière/.test(p.geo.town)).map((p) => I.project(p.geo.lat, p.geo.lng)[0]);
const north = deep.filter((p) => /Rodney Bay|Gros Islet|Cap Estate/.test(p.geo.town)).map((p) => I.project(p.geo.lat, p.geo.lng)[0]);
ok('Soufrière pins sit south-west of the northern ones', Math.max(...souf) < Math.min(...north));

/* ── 5. What the component emits ─────────────────────────────────────────── */
console.log('\n  THE MARKUP');
const w = { rainforest: 1, connection: 0.6 };
const pins = deep.slice(0, 5).map((p, i) => ({
  slug: p.slug, name: p.name, href: '/x#prop-' + p.slug, lat: p.geo.lat, lng: p.geo.lng, town: p.geo.town, approx: p.geo.approx,
  village: p.villages[0], villageName: p.villages[0], lead: i < 2, image: p.image, hook: p.hook
}));
const html = islandMap(I, pins, [{ key: 'rainforest', label: 'Nature & Renewal Village', lead: true }, { key: 'connection', label: 'Connection & Romance Village', lead: false }]);
ok('one <a data-pin> per pin, each a real link', (html.match(/<a href="\/x#prop-[^"]+" class="island-pin/g) || []).length === 5);
ok('one card per pin, exactly one visible', (html.match(/data-pin-card=/g) || []).length === 5 && (html.match(/data-pin-card="[^"]+" style="[^"]*"( hidden)?>/g) || []).filter((s) => !/hidden/.test(s)).length === 1);
ok('lead pins are labelled, receding ones are not', (html.match(/class="island-name"/g) || []).length === 2);
ok('the attribution is in <desc> and the caption', (html.match(/geoBoundaries/g) || []).length >= 2);
ok('the coordinates mark is the caption', /13°54′N 60°58′W/.test(html));
ok('the village accent rides the --v hook, never a literal colour', /--v: var\(--v-rainforest\)/.test(html) && !/#[0-9a-fA-F]{6}/.test(html.replace(/data:image[^"]*/g, '')));
ok('the legend is words, with the lead village marked', /chip--lead[^>]*>Nature &amp; Renewal Village/.test(html));
ok('an approximate pin says so in its card', pins.some((p) => p.approx) ? /placed from its address/.test(html) : true);
ok('no outline → no map, quietly', islandMap(null, pins, []) === '' && islandMap({}, pins, []) === '');

/* Two pins at one point (TheLifeCo sits inside A’ILA) are nudged apart. */
const a = deep.filter((p) => p.slug === 'aila-resorts-villas-residences')[0], t = deep.filter((p) => p.slug === 'thelifeco-st-lucia')[0];
if (a && t) {
  const two = islandMap(I, [a, t].map((p) => ({ slug: p.slug, name: p.name, lat: p.geo.lat, lng: p.geo.lng, village: 'longevity', lead: true })), []);
  const cx = (two.match(/class="island-dot" cx="(\d+)" cy="(\d+)"/g) || []);
  ok('coincident pins are nudged apart so both can be pointed at', cx.length === 2 && cx[0] !== cx[1], cx.join(' | '));
}

console.log('\n  ' + n + ' checks, ' + fails + ' failed\n');
process.exit(fails ? 1 : 0);
